def upgrade_schema_if_needed(conn: sqlite3.Connection) -> None:
    """Ensure image_path and source columns exist in commodity_presets table."""
    cursor = conn.cursor()
    cursor.execute("PRAGMA table_info(commodity_presets);")
    cols = {row[1] for row in cursor.fetchall()}
    
    if "image_path" not in cols:
        print("[MIGRATE] Adding column image_path to commodity_presets...")
        cursor.execute("ALTER TABLE commodity_presets ADD COLUMN image_path TEXT;")
    
    if "source" not in cols:
        print("[MIGRATE] Adding column source to commodity_presets...")
        cursor.execute("ALTER TABLE commodity_presets ADD COLUMN source TEXT;")
    
    conn.commit()


def seed_commodities(conn: sqlite3.Connection) -> int:
    """Idempotently inserts or updates commodity records."""
    cursor = conn.cursor()
    count_updated = 0
    count_inserted = 0
    
    for item in COMMODITY_DATA:
        cursor.execute("SELECT id FROM commodity_presets WHERE name = ?;", (item["name"],))
        row = cursor.fetchone()
        if row:
            # Update existing record
            cursor.execute("""
            UPDATE commodity_presets SET
                category = ?,
                moisture_sensitivity = ?,
                oxygen_sensitivity = ?,
                fat_content_level = ?,
                light_sensitivity = ?,
                recommended_temp_c = ?,
                recommended_rh_percent = ?,
                target_shelf_life_days = ?,
                puncture_risk = ?,
                typical_spoilage_mode = ?,
                critical_aw = ?,
                notes = ?,
                image_path = ?,
                source = ?
            WHERE id = ?;
            """, (
                item["category"],
                item["moisture_sensitivity"],
                item["oxygen_sensitivity"],
                item["fat_content_level"],
                item["light_sensitivity"],
                item["recommended_temp_c"],
                item["recommended_rh_percent"],
                item["target_shelf_life_days"],
                item["puncture_risk"],
                item["typical_spoilage_mode"],
                item["critical_aw"],
                item["notes"],
                item["image_path"],
                item["source"],
                row[0]
            ))
            count_updated += 1
        else:
            # Insert new record
            cursor.execute("""
            INSERT INTO commodity_presets (
                name, category, moisture_sensitivity, oxygen_sensitivity,
                fat_content_level, light_sensitivity, recommended_temp_c,
                recommended_rh_percent, target_shelf_life_days, puncture_risk,
                typical_spoilage_mode, critical_aw, notes, image_path, source
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
            """, (
                item["name"],
                item["category"],
                item["moisture_sensitivity"],
                item["oxygen_sensitivity"],
                item["fat_content_level"],
                item["light_sensitivity"],
                item["recommended_temp_c"],
                item["recommended_rh_percent"],
                item["target_shelf_life_days"],
                item["puncture_risk"],
                item["typical_spoilage_mode"],
                item["critical_aw"],
                item["notes"],
                item["image_path"],
                item["source"]
            ))
            count_inserted += 1
            
    conn.commit()
    print(f"[SEED] Finished seeding commodity_presets: {count_inserted} inserted, {count_updated} updated (Total: {len(COMMODITY_DATA)})")
    return len(COMMODITY_DATA)


